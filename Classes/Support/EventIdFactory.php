declare(strict_types=1);

namespace ViewMend\Typo3SiteTracker\Support;

final readonly class EventIdFactory
{
    /** @param list<string|int> $parts */
    public function deterministic(array $parts): string
    {
        $encoded = implode('|', array_map(
            static fn (string|int $part): string => (string) $part,
            $parts,
        ));

        return 'typo3-' . hash('sha256', $encoded);
    }

    public function random(string $purpose): string
    {
        $bytes = random_bytes(16);
        $bytes[6] = chr((ord($bytes[6]) & 0x0f) | 0x40);
        $bytes[8] = chr((ord($bytes[8]) & 0x3f) | 0x80);
        $hex = bin2hex($bytes);
        $uuid = sprintf(
            '%s-%s-%s-%s-%s',
            substr($hex, 0, 8),
            substr($hex, 8, 4),
            substr($hex, 12, 4),
            substr($hex, 16, 4),
            substr($hex, 20),
        );

        return sprintf('typo3-%s-%s', preg_replace('/[^a-z0-9]+/', '-', strtolower($purpose)), $uuid);
    }
}
